# Code inside Lights_UpdateActiveVehicles that the lighting-loop fix patches or jumps to.
SITES = [
    ("LightsLoop_Continue", 0x2F3BD),
    ("LightsLoop_GoneVehicleExit", 0x2F3FA),
]

VEHICLE_STATE_MAP = 0x7BDE0


class Image:
    def __init__(self, path):
        with open(path, "rb") as f:
            self.data = f.read()
        pe = struct.unpack_from("<I", self.data, 0x3C)[0]
        section_count = struct.unpack_from("<H", self.data, pe + 6)[0]
        optional_size = struct.unpack_from("<H", self.data, pe + 20)[0]
        optional = pe + 24
        self.timestamp = struct.unpack_from("<I", self.data, pe + 8)[0]
        self.image_size = struct.unpack_from("<I", self.data, optional + 56)[0]
        self.sections = []
        for i in range(section_count):
            header = optional + optional_size + i * 40
            name = self.data[header:header + 8].rstrip(b"\0").decode()
            virtual_size, rva, raw_size, raw = struct.unpack_from("<IIII", self.data, header + 8)
            self.sections.append((name, rva, max(virtual_size, raw_size), raw, virtual_size))
        reloc_rva, reloc_size = struct.unpack_from("<II", self.data, optional + 112 + 5 * 8)
        self.relocations = self._relocations(reloc_rva, reloc_size)

    def offset(self, rva):
        for _, start, size, raw, _ in self.sections:
            if start <= rva < start + size:
                return raw + rva - start
        raise SystemExit("RVA 0x%X is outside the file" % rva)

    def read(self, rva, length):
        at = self.offset(rva)
        return self.data[at:at + length]

    def section(self, name):
        for section_name, rva, _, _, virtual_size in self.sections:
            if section_name == name:
                return rva, rva + virtual_size
        raise SystemExit("no %s section" % name)

    def _relocations(self, rva, size):
        result = []
        at = self.offset(rva)
        end = at + size
        while at < end:
            page, block_size = struct.unpack_from("<II", self.data, at)
            if block_size == 0:
                break
            for i in range((block_size - 8) // 2):
                entry = struct.unpack_from("<H", self.data, at + 8 + 2 * i)[0]
                if entry >> 12:
                    result.append(page + (entry & 0xFFF))
            at += block_size
        return result


def signature_rows(image, entries):
    rows = []
    for name, rva in entries:
        if any(rva - 8 < r < rva + SIGNATURE_LENGTH for r in image.relocations):
            raise SystemExit("%s: a relocation falls inside its signature" % name)
        data = ", ".join("0x%02X" % b for b in image.read(rva, SIGNATURE_LENGTH))
        rows.append('        { "%s", 0x%X, { %s } },' % (name, rva, data))
    return rows


def enum_rows(entries):
    return ["        %s," % name for name, _ in entries]


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    image = Image(sys.argv[1])
    code_start, code_end = image.section(".text")

    lines = [
        "// Generated by tools/gen_layout.py from ELS.asi V 1.05. Do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace els",
        "{",
        "    inline constexpr uint32_t kTimestamp = 0x%08X;" % image.timestamp,
        "    inline constexpr uint32_t kImageSize = 0x%X;" % image.image_size,
        "    inline constexpr uint32_t kCodeStart = 0x%X;" % code_start,
        "    inline constexpr uint32_t kCodeEnd = 0x%X;" % code_end,
        "    inline constexpr uint32_t kVehicleStateMap = 0x%X;" % VEHICLE_STATE_MAP,
        "    inline constexpr int kSignatureLength = %d;" % SIGNATURE_LENGTH,
        "",
        "    struct Signature",
        "    {",
        "        const char* name;",
        "        uint32_t rva;",
        "        uint8_t bytes[kSignatureLength];",
        "    };",
        "",
        "    enum class Function",
        "    {",
    ] + enum_rows(FUNCTIONS) + [
        "        Count",
        "    };",
        "",
        "    enum class Site",
        "    {",
    ] + enum_rows(SITES) + [
        "        Count",
        "    };",
        "",
        "    inline constexpr Signature kFunctions[] =",
        "    {",
    ] + signature_rows(image, FUNCTIONS) + [
        "    };",
        "",
        "    inline constexpr Signature kSites[] =",
        "    {",
    ] + signature_rows(image, SITES) + [
        "    };",
        "",
        "    static_assert(sizeof(kFunctions) / sizeof(kFunctions[0]) == static_cast<size_t>(Function::Count));",
        "    static_assert(sizeof(kSites) / sizeof(kSites[0]) == static_cast<size_t>(Site::Count));",
        "}",
        "",
    ]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("Wrote %s (timestamp %08X, %d functions, %d sites)" % (os.path.normpath(OUTPUT), image.timestamp,
                                                                 len(FUNCTIONS), len(SITES)))


if __name__ == "__main__":
    main()
